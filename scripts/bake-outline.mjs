#!/usr/bin/env node
// Bake a candy's front silhouette from assets/candies/<slug>/hero.png alpha into a 2D signed distance grid
// (src/three/candies/<slug>.outline.json) that candy modules extrude into 3D. Only the outline is stored,
// never photo pixels. Units: world, with the silhouette's HEIGHT = 1 and origin at the bbox centre;
// negative = inside. Usage: node scripts/bake-outline.mjs <slug> [rows=160] [blurPx=2]
import sharp from 'sharp';
import { writeFile } from 'node:fs/promises';

const [, , slug, rowsArg = '160', blurArg = '2'] = process.argv;
const ROWS = Number(rowsArg), BLUR = Number(blurArg), PAD = 0.06; // pad in world units around the bbox
const src = `assets/candies/${slug}/hero.png`;
const { data, info } = await sharp(src).ensureAlpha().extractChannel(3).blur(BLUR > 0.3 ? BLUR : undefined).raw().toBuffer({ resolveWithObject: true });
const W = info.width, H = info.height;
let x0 = W, y0 = H, x1 = 0, y1 = 0;
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (data[y * W + x] >= 128) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
const bh = y1 - y0 + 1, bw = x1 - x0 + 1, s = 1 / bh; // world units per source px

// exact Euclidean distance transform (Felzenszwalb & Huttenlocher), squared distances in px
function edt(mask) { // mask[i] = true where the feature set is
  const INF = 1e20, f = new Float64Array(W * H);
  for (let i = 0; i < W * H; i++) f[i] = mask[i] ? 0 : INF;
  const d1 = (g, n) => {
    const d = new Float64Array(n), v = new Int32Array(n), z = new Float64Array(n + 1); let k = 0; v[0] = 0; z[0] = -INF; z[1] = INF;
    for (let q = 1; q < n; q++) {
      let p = (g[q] + q * q - (g[v[k]] + v[k] * v[k])) / (2 * q - 2 * v[k]);
      while (p <= z[k]) { k--; p = (g[q] + q * q - (g[v[k]] + v[k] * v[k])) / (2 * q - 2 * v[k]); }
      k++; v[k] = q; z[k] = p; z[k + 1] = INF;
    }
    k = 0; for (let q = 0; q < n; q++) { while (z[k + 1] < q) k++; d[q] = (q - v[k]) ** 2 + g[v[k]]; }
    return d;
  };
  const col = new Float64Array(H);
  for (let x = 0; x < W; x++) { for (let y = 0; y < H; y++) col[y] = f[y * W + x]; const d = d1(col, H); for (let y = 0; y < H; y++) f[y * W + x] = d[y]; }
  const row = new Float64Array(W);
  for (let y = 0; y < H; y++) { for (let x = 0; x < W; x++) row[x] = f[y * W + x]; const d = d1(row, W); for (let x = 0; x < W; x++) f[y * W + x] = d[x]; }
  return f;
}
const inside = Array.from(data, (a) => a >= 128);
const dOut = edt(inside), dIn = edt(inside.map((v) => !v));
const sdfAt = (x, y) => { // bilinear in source px, world units
  const xi = Math.min(Math.max(Math.floor(x), 0), W - 2), yi = Math.min(Math.max(Math.floor(y), 0), H - 2), fx = x - xi, fy = y - yi;
  const v = (i, j) => { const k = j * W + i; return (Math.sqrt(dOut[k]) - Math.sqrt(dIn[k])) * s; };
  return (v(xi, yi) * (1 - fx) + v(xi + 1, yi) * fx) * (1 - fy) + (v(xi, yi + 1) * (1 - fx) + v(xi + 1, yi + 1) * fx) * fy;
};
// sample grid covering bbox + pad, world y up
const halfW = (bw * s) / 2 + PAD, halfH = 0.5 + PAD, cell = (2 * halfH) / (ROWS - 1);
const cols = Math.round((2 * halfW) / cell) + 1;
const cx = x0 + bw / 2, cy = y0 + bh / 2;
const grid = new Int16Array(cols * ROWS), Q = 8192;
for (let j = 0; j < ROWS; j++) for (let i = 0; i < cols; i++) {
  const wx = -halfW + i * cell, wy = halfH - j * cell; // row 0 = top
  const d = sdfAt(cx + wx / s, cy - wy / s);
  grid[j * cols + i] = Math.max(-32767, Math.min(32767, Math.round(d * Q)));
}
const out = {
  _readme: `Generated by scripts/bake-outline.mjs from ${src} (alpha only). Do not edit; re-bake instead.`,
  slug, cols, rows: ROWS, cell, minX: -halfW, maxY: halfH, quant: Q, aspect: bw / bh,
  source: { w: W, h: H, bbox: [x0, y0, bw, bh] },
  data: Buffer.from(grid.buffer).toString('base64'),
};
const path = `src/three/candies/${slug}.outline.json`;
await writeFile(path, JSON.stringify(out) + '\n');
console.log(`wrote ${path}: ${cols}x${ROWS} cells, aspect ${out.aspect.toFixed(3)}, ${(JSON.stringify(out).length / 1024).toFixed(1)} kB`);
